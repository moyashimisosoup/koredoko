export function buildListingExtractionPrompt(rawUrl) {
 if(typeof rawUrl!=="string" || rawUrl.trim().length===0)throw Error("不動産広告のURLを入力してください。");
 if(rawUrl.length>2048)throw Error("URLが長すぎます（2048文字以内）。");
 if(/[\r\n]/.test(rawUrl))throw Error("URLに改行を含めないでください。");
 let url;
 try { url=new URL(rawUrl.trim()); } catch {throw Error("URLの形式を確認してください。");}
 if(!["https:","http:"].includes(url.protocol)||!url.hostname)throw Error("http:// または https:// で始まるURLを入力してください。");
 if(url.username||url.password)throw Error("認証情報を含むURLは使用できません。");
 url.hash="";
 return TEMPLATE.map(line=>line==="[[URL]]"?url.href:line).join("\n");
}
